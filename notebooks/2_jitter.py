def avaliar_pasta_jitter(pred_dir: Path, nomes: list, n_prompts: int, root_ds=KVASIR):
    dices_k, ious_k, erros_k = [], [], []
    for k in range(n_prompts):
        d_l, i_l, e_l = [], [], []
        for n in nomes:
            gt = ler_mascara(n, root_ds)
            if (gt > 0).sum() == 0:
                continue
            f = pred_dir / f"{n}_p{k}.png"
            if not f.exists():
                cands = list(pred_dir.glob(f"*{n}*.png"))
                if not cands:
                    continue
                f = cands[0]
            p = cv2.imread(str(f), cv2.IMREAD_GRAYSCALE)
            if p.shape != gt.shape:
                p = cv2.resize(p, (gt.shape[1], gt.shape[0]), interpolation=cv2.INTER_NEAREST)
            p_bin = (p > 127).astype(np.uint8)
            d_l.append(dice(gt, p_bin))
            i_l.append(iou(gt, p_bin))
            a_r, a_p = (gt > 0).sum(), (p_bin > 0).sum()
            e_l.append(abs(float(a_p) - float(a_r)) / (float(a_r) + 1e-7))
        dices_k.append(d_l)
        ious_k.append(i_l)
        erros_k.append(e_l)
    arr_d = np.array(dices_k)
    mean_d = arr_d.mean(axis=0)
    std_intra = arr_d.std(axis=0).mean() if n_prompts > 1 else 0.0
    return (
        float(mean_d.mean()),
        float(np.mean(ious_k)),
        float(np.mean(erros_k)),
        float((mean_d < 0.5).mean() * 100.0),
        float(std_intra),
    )


