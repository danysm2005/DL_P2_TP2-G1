CONFIGS_FT = {
    "caixa": [("caixa", 0.0, 1), ("caixa", 0.05, 5), ("caixa", 0.10, 5), ("caixa", 0.20, 5)],
    "ponto_centro": [("ponto_centro", 0.0, 1), ("ponto_aleatorio", 0.0, 5)],
}


def carregar_decoder(pred, run: Path):
    sd = torch.load(run / "decoder.pt", map_location="cuda")
    dec = pred.model.sam_mask_decoder if hasattr(pred.model, "sam_mask_decoder") else pred.model.mask_decoder
    dec.load_state_dict(sd)  # estrito: falha se as chaves não baterem


def dice_iou(gt, m):
    g, p = gt > 0, m > 0
    i = (g & p).sum()
    return (2 * i + 1e-7) / (g.sum() + p.sum() + 1e-7), (i + 1e-7) / ((g | p).sum() + 1e-7)


rows = []
for mod in ["sam_vit_b", "sam2_hiera_s"]:
    pred = carregar_sam(mod, CK[mod], "cuda")
    for prm in ["caixa", "ponto_centro"]:
        for s in (1, 2, 3):
            carregar_decoder(pred, BASE / f"runs_SAMfine/{mod}_{prm}/split{s}_seed{s}")
            print(f"{mod} | {prm} | seed {s}", flush=True)
            for i, n in enumerate(carregar_divisao(s)["test"]):
                img, gt = ler_imagem(n), ler_mascara(n)
                pred.set_image(img)
                for tipo, j, reps in CONFIGS_FT[prm]:
                    for k in range(reps):
                        rng = np.random.default_rng([0, i, k])  # mesma convenção do zero-shot
                        if tipo == "caixa":
                            kw = dict(box=caixa(gt, j, rng))
                        elif tipo == "ponto_centro":
                            kw = dict(zip(("point_coords", "point_labels"), ponto(gt, True)))
                        else:
                            kw = dict(zip(("point_coords", "point_labels"), ponto(gt, False, rng)))
                        masks, _, _ = pred.predict(multimask_output=False, **kw)
                        d, u = dice_iou(gt, masks[0])
                        rows.append((mod, prm, s, tipo, j, k, n, d, u))
    del pred
    torch.cuda.empty_cache()

df = pd.DataFrame(rows, columns=["modelo", "prompt_treino", "seed", "tipo", "jitter", "rep", "stem", "dice", "iou"])
df.to_csv(OUT / "jitter_fine_tuning_por_imagem.csv", index=False)

chave = ["modelo", "prompt_treino", "tipo", "jitter"]
img_df = (
    df.groupby(chave + ["seed", "stem"])
    .agg(m=("dice", "mean"), sd=("dice", lambda x: np.std(x, ddof=0)), iou=("iou", "mean"))
    .reset_index()
)
seed_df = (
    img_df.groupby(chave + ["seed"])
    .agg(mDice=("m", "mean"), mIoU=("iou", "mean"), dp_intra=("sd", "mean"), falhas=("m", lambda x: (x < 0.5).mean() * 100))
    .reset_index()
)
tab = (
    seed_df.groupby(chave)
    .agg(
        mDice_med=("mDice", "mean"),
        mDice_dp=("mDice", "std"),
        mIoU_med=("mIoU", "mean"),
        mIoU_dp=("mIoU", "std"),
        dp_intra=("dp_intra", "mean"),
        falhas=("falhas", "mean"),
    )
    .reset_index()
)
tab["mDice (Média ± DP)"] = tab.mDice_med.map("{:.4f}".format) + " ± " + tab.mDice_dp.map("{:.4f}".format)
tab.to_csv(OUT / "tabela_jitter_fine_tuning.csv", index=False)
