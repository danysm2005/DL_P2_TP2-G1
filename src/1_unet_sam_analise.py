from tensorflow.keras import layers, Model
from classification_models.tfkeras import Classifiers   # tfkeras, não keras

ResNet34, _ = Classifiers.get("resnet34")
IMG_SIZE = (352, 352)

def conv_block(x, filters):
    for _ in range(2):
        x = layers.Conv2D(filters, 3, padding="same", use_bias=False)(x)
        x = layers.BatchNormalization()(x)
        x = layers.Activation("relu")(x)
    return x

def decoder_block(x, skip, filters):
    x = layers.Conv2DTranspose(filters, 2, strides=2, padding="same")(x)
    if x.shape[1] != skip.shape[1] or x.shape[2] != skip.shape[2]:
        x = layers.Resizing(skip.shape[1], skip.shape[2])(x)
    x = layers.Concatenate()([x, skip])
    return conv_block(x, filters)

def build_model(img_size=IMG_SIZE):
    inputs = keras.Input(shape=img_size + (3,))
    x = layers.Rescaling(255.0)(inputs)          # imagens em [0,1] -> 0-255

    backbone = ResNet34(input_tensor=x, weights="imagenet", include_top=False)

    s1 = inputs                                              # 352
    s2 = backbone.get_layer("relu0").output                  # 176
    s3 = backbone.get_layer("stage2_unit1_relu1").output     #  88
    s4 = backbone.get_layer("stage3_unit1_relu1").output     #  44
    s5 = backbone.get_layer("stage4_unit1_relu1").output     #  22
    bn = backbone.get_layer("relu1").output                  #  11
    bn = layers.Dropout(0.3)(bn)

    d1 = decoder_block(bn, s5, 256)   # 22
    d2 = decoder_block(d1, s4, 128)   # 44
    d3 = decoder_block(d2, s3, 64)    # 88
    d4 = decoder_block(d3, s2, 32)    # 176
    d5 = decoder_block(d4, s1, 16)    # 352

    outputs = layers.Conv2D(1, 1, activation="sigmoid")(d5)
    return Model(inputs, outputs, name="ResNet34_UNet"), backbone

def set_encoder_trainable(backbone, trainable):
    for l in backbone.layers:
        # BatchNorm do encoder fica sempre congelada (mais estável)
        l.trainable = trainable and not isinstance(l, layers.BatchNormalization)

def dice_loss(y_true, y_pred, eps=1e-7):
    y_true = tf.cast(y_true, tf.float32)
    inter = tf.reduce_sum(y_true * y_pred, axis=(1, 2, 3))
    union = tf.reduce_sum(y_true, axis=(1, 2, 3)) + tf.reduce_sum(y_pred, axis=(1, 2, 3))
    return 1 - tf.reduce_mean((2 * inter + eps) / (union + eps))

def dice_bce(y_true, y_pred):
    return dice_loss(y_true, y_pred) + keras.losses.binary_crossentropy(y_true, y_pred)

def compile_model(model, lr):
    model.compile(optimizer=keras.optimizers.Adam(lr), loss=dice_bce)

