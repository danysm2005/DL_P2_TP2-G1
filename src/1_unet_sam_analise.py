# ----- métricas -----
def _stats(y_true, y_pred, thr=0.5):
    y_true = tf.cast(y_true > 0.5, tf.float32)
    y_pred = tf.cast(y_pred > thr, tf.float32)
    inter = tf.reduce_sum(y_true * y_pred, axis=(1, 2, 3))
    t = tf.reduce_sum(y_true, axis=(1, 2, 3))
    p = tf.reduce_sum(y_pred, axis=(1, 2, 3))
    return inter, t, p

def mdice(y_true, y_pred):
    inter, t, p = _stats(y_true, y_pred)
    return tf.reduce_mean((2.0 * inter + 1e-7) / (t + p + 1e-7))

def miou(y_true, y_pred):
    inter, t, p = _stats(y_true, y_pred)
    return tf.reduce_mean((inter + 1e-7) / (t + p - inter + 1e-7))

def compile_model(model, lr):
    model.compile(optimizer=keras.optimizers.Adam(lr), loss=dice_bce,
                  metrics=[mdice, miou])

# ----- dados -----
def carregar(stem):
    img = tf.io.decode_jpeg(tf.io.read_file(tf.strings.join([PI, "/", stem, ".jpg"])), channels=3)
    msk = tf.io.decode_jpeg(tf.io.read_file(tf.strings.join([PM, "/", stem, ".jpg"])), channels=1)
    img = tf.image.resize(img, IMG) / 255.0
    msk = tf.image.resize(msk, IMG, method="nearest")
    msk = tf.cast(msk > 127, tf.float32)
    return img, msk

def augment(img, msk):
    x = tf.concat([img, msk], axis=-1)

    # 1. Flips espelhados
    x = tf.image.random_flip_left_right(x)
    x = tf.image.random_flip_up_down(x)

    # 2. Rotações ortogonais aleatórias (0, 90, 180 ou 270 graus)
    k = tf.random.uniform([], minval=0, maxval=4, dtype=tf.int32)
    x = tf.image.rot90(x, k=k)

    img_aug, msk_aug = x[..., :3], x[..., 3:]

    # 3. Variação de iluminação (apenas na imagem, nunca na máscara)
    img_aug = tf.image.random_brightness(img_aug, max_delta=0.1)
    img_aug = tf.image.random_contrast(img_aug, lower=0.8, upper=1.2)
    img_aug = tf.clip_by_value(img_aug, 0.0, 1.0)

    return img_aug, msk_aug

def fazer_ds(stems, treino, bs=16):
    ds = tf.data.Dataset.from_tensor_slices(stems)
    ds = ds.map(carregar, num_parallel_calls=tf.data.AUTOTUNE).cache()
    if treino:
        ds = ds.shuffle(len(stems), seed=SEED).map(augment, num_parallel_calls=tf.data.AUTOTUNE)
    return ds.batch(bs).prefetch(tf.data.AUTOTUNE)

