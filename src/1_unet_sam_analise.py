def avaliar(model, stems, thrs=(0.3, 0.4, 0.5, 0.6, 0.7)):
    D = np.zeros((len(thrs), len(stems)))
    I = np.zeros((len(thrs), len(stems)))
    for j, stem in enumerate(stems):
        img = tf.io.decode_jpeg(tf.io.read_file(f"{PI}/{stem}.jpg"), channels=3)
        gt = tf.io.decode_jpeg(tf.io.read_file(f"{PM}/{stem}.jpg"), channels=1).numpy()[..., 0] > 127
        x = tf.image.resize(img, IMG) / 255.0
        p = model.predict(x[None], verbose=0)[0]
        p = tf.image.resize(p, gt.shape).numpy()[..., 0]
        for i, t in enumerate(thrs):
            pr = p > t
            inter = (gt & pr).sum()
            D[i, j] = (2.0 * inter + 1e-7) / (gt.sum() + pr.sum() + 1e-7)
            I[i, j] = (inter + 1e-7) / ((gt | pr).sum() + 1e-7)
    for i, t in enumerate(thrs):
        print(f"thr={t}: mDice={D[i].mean():.4f}  mIoU={I[i].mean():.4f}")
    best = int(D.mean(1).argmax())
    print(f"-> melhor threshold na validação: {thrs[best]}")
    return thrs[best], D[best], I[best]

